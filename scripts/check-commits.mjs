#!/usr/bin/env node
// Checks commits before they become public: a personal e-mail address or a
// stray trailer that slips into one commit stays in the public history for good.
//
// For every commit in <base>..<head>:
//   - the author and the committer e-mail are one of: a personal GitHub noreply
//     address (<digits>+<login> at users.noreply.github.com), GitHub's own
//     noreply address (committer of web merges), or Dependabot's address. Any
//     other bot login ("<login>[bot]") is refused;
//   - every e-mail address anywhere in the message (subject and body) follows
//     the same rule. The only exception is GitHub's support address in the
//     sign-off that Dependabot writes;
//   - trailers: only two are accepted, each with exactly one value. A
//     Co-Authored-By trailer must name the maintainer's own co-author account
//     (CO_AUTHOR below); a Signed-off-by trailer must be Dependabot's sign-off.
//     One exception: the Co-Authored-By trailer that GitHub adds when it
//     squashes a Dependabot pull request (DEPENDABOT_CO_AUTHOR below) is
//     accepted on a commit whose author address is Dependabot's, and on no
//     other. Any other key, a trailer without an address, or any other value
//     is refused. Trailers are parsed by git itself (`git interpret-trailers
//     --parse --no-divider`), so a "key: value" line inside the body, such as
//     the YAML block of a Dependabot message, is not mistaken for a trailer;
//     a Co-Authored-By or Signed-off-by line anywhere else in the message must
//     carry an accepted value as well;
//   - no line looks like a generated-by footer: a line that starts with
//     "generated with" or "generated by" (any case, a hyphen counts as a
//     space, leading symbols ignored), or a line with the robot emoji.
//
// The raw addresses of the commit objects are read (%ae/%ce), not the ones a
// .mailmap rewrites for display.
//
// No address is written literally in this file: the repository check
// (scripts/check-tree.mjs) refuses e-mail addresses in tracked files, so every
// address is put together from its parts at run time.
//
// Usage: node scripts/check-commits.mjs <base> <head>
//   <base> of all zeros means: every commit reachable from <head> (CI uses this
//   on pushes and on runs started by hand, so a cancelled earlier run never
//   leaves commits unchecked).
// Exit codes: 0 clean, 1 violations found (all listed), 2 usage or git error.

import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { findEmails } from './check-dist.mjs';

const AT = '@';
const NOREPLY_DOMAIN = 'users.noreply.github.com';

/**
 * The noreply address of a GitHub account.
 * @param {string} id
 * @param {string} login
 */
export const noreplyAddress = (id, login) => `${id}+${login}${AT}${NOREPLY_DOMAIN}`;

/** A personal noreply address: <digits>+<login>, where a login has letters, digits and inner hyphens only. */
export const PERSONAL_NOREPLY_RE = /^\d+\+[a-z0-9](?:[a-z0-9-]*[a-z0-9])?@users\.noreply\.github\.com$/i;

/** Any bot noreply address: <digits>+<login>[bot]. */
const BOT_NOREPLY_RE = /^\d+\+[^@\s]*\[bot\]@users\.noreply\.github\.com$/i;

/** GitHub's own noreply address (committer of web merges). */
export const GITHUB_NOREPLY = `noreply${AT}github.com`;

/** Dependabot's address (account id 49699333); the only bot accepted. */
export const DEPENDABOT_ADDRESS = noreplyAddress('49699333', 'dependabot[bot]');

/** The one Co-Authored-By value accepted: the maintainer's co-author account (id 310343018). */
export const CO_AUTHOR = `xevbor <${noreplyAddress('310343018', 'xevbor')}>`;

/**
 * The Co-Authored-By value GitHub adds when it squashes a Dependabot pull request;
 * accepted only on a commit whose author address is exactly DEPENDABOT_ADDRESS.
 */
export const DEPENDABOT_CO_AUTHOR = `dependabot[bot] <${DEPENDABOT_ADDRESS}>`;

/** The sign-off Dependabot writes; the only place GitHub's support address may appear. */
export const DEPENDABOT_SIGN_OFF = `dependabot[bot] <support${AT}github.com>`;

/** The accepted trailers: key (compared without regard to case) and its one accepted value. */
export const TRAILERS = [
  { key: 'Co-Authored-By', value: CO_AUTHOR, refusal: 'co-author trailers are not accepted' },
  { key: 'Signed-off-by', value: DEPENDABOT_SIGN_OFF, refusal: "Signed-off-by is accepted only as Dependabot's sign-off" },
];

/** A footer line: "generated with" or "generated by" at the start, after any symbols. */
const FOOTER_RE = /^[^\p{L}\p{N}]*generated[\s-]+(?:with|by)\b/iu;
const ROBOT = '\u{1F916}';

/**
 * @typedef {{ sha: string, authorEmail: string, committerEmail: string, subject: string, message: string }} Commit
 * @typedef {{ key: string, value: string }} Trailer
 * @typedef {{ sha: string, rule: string, message: string }} Violation
 * @typedef {{ cwd?: string, env?: NodeJS.ProcessEnv }} GitOptions
 */

/**
 * Why an address is refused, or null when it is accepted.
 * @param {string} address
 * @returns {string | null}
 */
export function addressProblem(address) {
  const a = address.toLowerCase();
  if (a === GITHUB_NOREPLY || a === DEPENDABOT_ADDRESS.toLowerCase() || PERSONAL_NOREPLY_RE.test(a)) return null;
  if (BOT_NOREPLY_RE.test(a)) return 'is a bot address, and only Dependabot is accepted';
  return 'is not a GitHub noreply address';
}

/** @param {string} address */
export const allowedAddress = (address) => addressProblem(address) === null;

/**
 * @param {string[]} args
 * @param {GitOptions} opts
 * @param {string} [input]
 */
function git(args, opts, input) {
  return execFileSync('git', args, {
    cwd: opts.cwd,
    env: opts.env ?? process.env,
    encoding: 'utf8',
    input,
    stdio: [input === undefined ? 'ignore' : 'pipe', 'pipe', 'pipe'],
    maxBuffer: 64 * 1024 * 1024,
  });
}

/**
 * Resolves `rev` to a commit SHA or throws a clear error.
 * @param {string} rev
 * @param {GitOptions} opts
 */
export function commitSha(rev, opts) {
  try {
    return git(['rev-parse', '--verify', '--quiet', '--end-of-options', `${rev}^{commit}`], opts).trim();
  } catch {
    throw new Error(`"${rev}" is not a commit in this repository (is the history fetched? use fetch-depth: 0)`);
  }
}

/** @param {string} base */
export const isAllZeros = (base) => /^0+$/.test(base);

/**
 * Commits in base..head, oldest first; an all-zero base means every commit of head.
 * @param {string} base
 * @param {string} head
 * @param {GitOptions} [opts]
 * @returns {Commit[]}
 */
export function listCommits(base, head, opts = {}) {
  const headSha = commitSha(head, opts);
  const range = isAllZeros(base) ? [headSha] : [`${commitSha(base, opts)}..${headSha}`];
  const out = git(['log', '--reverse', '--no-mailmap', '--format=%H%x1f%ae%x1f%ce%x1f%B%x1e', ...range, '--'], opts);
  return out
    .split('\x1e')
    .map((rec) => rec.replace(/^\n/, ''))
    .filter((rec) => rec !== '')
    .map((rec) => {
      const [sha = '', authorEmail = '', committerEmail = '', message = ''] = rec.split('\x1f');
      return { sha, authorEmail, committerEmail, subject: message.split('\n')[0] ?? '', message };
    });
}

/**
 * The trailers of a commit message, as git reads them.
 * @param {string} message
 * @param {GitOptions} [opts]
 * @returns {Trailer[]}
 */
export function parseTrailers(message, opts = {}) {
  const out = git(['interpret-trailers', '--parse', '--no-divider'], opts, message);
  return out
    .split('\n')
    .filter((line) => line.trim() !== '')
    .map((line) => {
      const sep = line.indexOf(':');
      return sep === -1 ? { key: line.trim(), value: '' } : { key: line.slice(0, sep).trim(), value: line.slice(sep + 1).trim() };
    });
}

/** @param {string} text */
const clip = (text) => (text.length > 80 ? `${text.slice(0, 77)}...` : text);

/**
 * @param {Commit} c
 * @param {Trailer[]} trailers
 * @returns {Violation[]}
 */
export function checkCommit(c, trailers) {
  /** @type {Violation[]} */
  const violations = [];
  const short = c.sha.slice(0, 12);
  /** @param {string} rule @param {string} message */
  const add = (rule, message) => violations.push({ sha: c.sha, rule, message: `${short} "${c.subject}": ${message}` });

  const author = addressProblem(c.authorEmail);
  if (author) add('author', `author e-mail <${c.authorEmail}> ${author}`);
  const committer = addressProblem(c.committerEmail);
  if (committer) add('committer', `committer e-mail <${c.committerEmail}> ${committer}`);

  // Trailers as git reads them, plus any Co-Authored-By or Signed-off-by line
  // elsewhere in the message: each distinct key and value is judged once.
  const lines = c.message.split('\n');
  const keyed = lines.flatMap((line) => {
    const m = /^\s*([A-Za-z0-9-]+)\s*:\s*(.*?)\s*$/.exec(line);
    const rule = m && TRAILERS.find((t) => t.key.toLowerCase() === (m[1] ?? '').toLowerCase());
    return m && rule ? [{ key: m[1] ?? '', value: m[2] ?? '' }] : [];
  });
  // GitHub's squash of a Dependabot pull request names Dependabot as co-author:
  // that one value, on a commit Dependabot authored, and nowhere else.
  const isDependabotCoAuthor = (/** @type {Trailer} */ t) =>
    c.authorEmail === DEPENDABOT_ADDRESS && t.key.toLowerCase() === 'co-authored-by' && t.value === DEPENDABOT_CO_AUTHOR;
  const seen = new Set();
  for (const t of [...trailers, ...keyed]) {
    const id = `${t.key.toLowerCase()}\n${t.value}`;
    if (seen.has(id)) continue;
    seen.add(id);
    const rule = TRAILERS.find((r) => r.key.toLowerCase() === t.key.toLowerCase());
    if (!rule) {
      add('trailer', `trailer "${t.key}" is not allowed (only ${TRAILERS.map((r) => r.key).join(' and ')})`);
    } else if (!/<[^<>\s]+@[^<>\s]+>/.test(t.value)) {
      add('trailer', `trailer "${t.key}: ${clip(t.value)}" has no address`);
    } else if (t.value !== rule.value && !isDependabotCoAuthor(t)) {
      add('trailer', `trailer "${t.key}: ${clip(t.value)}" is not accepted: ${rule.refusal}`);
    }
  }

  // Dependabot's own sign-off is the one place GitHub's support address may appear.
  const isDependabotSignOff = (/** @type {string} */ line) =>
    /^\s*signed-off-by\s*:\s*(.*?)\s*$/i.exec(line)?.[1] === DEPENDABOT_SIGN_OFF;
  const text = lines.filter((l) => !isDependabotSignOff(l)).join('\n');
  const addresses = new Set([
    ...[...text.matchAll(/<([^<>\s]+@[^<>\s]+)>/g)].map((m) => m[1] ?? ''),
    ...[...findEmails(text)].map((m) => m.value),
    // A bot address outside angle brackets: the general finder stops at "[bot]".
    ...[...text.matchAll(/\d+\+[A-Za-z0-9-]+\[bot\]@users\.noreply\.github\.com/gi)].map((m) => m[0]),
  ]);
  for (const address of addresses) {
    const problem = addressProblem(address);
    if (problem) add('message', `the message contains <${address}>, which ${problem}`);
  }

  lines.forEach((line, i) => {
    if (FOOTER_RE.test(line) || line.includes(ROBOT)) {
      add('footer', `line ${i + 1} looks like a generated-by footer: "${clip(line.trim())}"`);
    }
  });
  return violations;
}

/**
 * @param {Commit[]} commits
 * @param {GitOptions} [opts]
 * @returns {Violation[]}
 */
export function checkCommits(commits, opts = {}) {
  return commits.flatMap((c) => checkCommit(c, parseTrailers(c.message, opts)));
}

/** @param {string[]} argv */
function main(argv) {
  const [base, head, ...rest] = argv;
  if (!base || !head || rest.length > 0) {
    console.error('usage: node scripts/check-commits.mjs <base> <head>   (npm run check:commits -- <base> <head>)');
    return 2;
  }
  /** @type {Violation[]} */
  let violations;
  /** @type {Commit[]} */
  let commits;
  try {
    commits = listCommits(base, head);
    violations = checkCommits(commits);
  } catch (err) {
    console.error(`check:commits: ${err instanceof Error ? err.message : String(err)}`);
    return 2;
  }
  const what = isAllZeros(base) ? `all commits of ${head}` : `${base}..${head}`;
  if (violations.length === 0) {
    console.log(
      `check:commits: ${commits.length} commit(s) in ${what}: GitHub noreply addresses only, no trailers but the accepted ones, no generated-by footers`,
    );
    return 0;
  }
  console.error(`check:commits: ${violations.length} violation(s) in ${commits.length} commit(s) of ${what}:`);
  for (const v of violations) console.error(`  [${v.rule}] ${v.message}`);
  console.error('The rules and how to fix a commit: docs/contributing.md, section "Commits".');
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
